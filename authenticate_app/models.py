# LOGIN HISTORY (Tenant-aware audit)
# ==========================================================
class LoginHistory(models.Model):
    """
    Tracks user login activity with tenant context for auditing/security.
    
    Attributes:
        user (ForeignKey): User who logged in.
        organization (ForeignKey): Organization context.
        branch (ForeignKey): Optional branch context.
        ip_address (GenericIPAddressField): IP address of login.
        timestamp (DateTimeField): When the login occurred.
    """

    # Step 1: User who logged in
    user = models.ForeignKey(User, on_delete=models.CASCADE)

    # Step 2: Tenant context (organization + optional branch)
    organization = models.ForeignKey(Organization, on_delete=models.CASCADE)
    branch = models.ForeignKey(Branch, on_delete=models.SET_NULL, null=True, blank=True)

    # Step 3: IP address of login
    ip_address = models.GenericIPAddressField()

    # Step 4: Timestamp of login
    timestamp = models.DateTimeField(auto_now_add=True)

    # Step 5: String representation for admin/debugging
    def __str__(self):
        return f"{self.user.username} | {self.organization.name} | {self.ip_address} | {self.timestamp}"

    class Meta:
        # Step 6: Indexes for faster queries by org/user/IP/timestamp
        indexes = [
            models.Index(fields=["organization", "timestamp"]),
            models.Index(fields=["user", "timestamp"]),
            models.Index(fields=["ip_address"]),
        ]