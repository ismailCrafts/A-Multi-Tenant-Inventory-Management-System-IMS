# USER (Tenant + Platform Admin auth)
# ==========================================================
class User(AbstractUser):
    # Username is the login field — unique per org, NOT globally unique
    username = models.CharField(max_length=150)
    
    profile_image = models.ImageField(
        upload_to="profiles/",
        null=True,
        blank=True
    )
    phone = models.CharField(max_length=20, null=True, blank=True)

    # Email is kept for password reset / contact — unique per org, NOT globally unique
    email = models.EmailField()

    # Use username as the login identifier
    USERNAME_FIELD = "username"
    REQUIRED_FIELDS = ["email"]

    # Role — matches migration 0006_alter_user_role exactly
    # DO NOT change choices without a new migration
    ROLE_CHOICES = [
        ('platform_admin', 'Platform Admin'),
        ('admin',          'Organization Admin'),
        ('manager',        'Inventory Manager'),
        ('employee',       'Employee'),
    ]
    role = models.CharField(
        max_length=20,
        choices=ROLE_CHOICES,
        default='employee',
    )

    organization = models.ForeignKey(
        'authenticate_app.Organization',
        on_delete=models.CASCADE,
        related_name="users",
        null=True, blank=True
    )

    branch = models.ForeignKey(
        'authenticate_app.Branch',
        on_delete=models.SET_NULL,
        null=True, blank=True,
        related_name="users"
    )

    class Meta:
        # username unique per org, email unique per org — NOT globally unique
        unique_together = [
            ("username", "organization"),
            ("email", "organization"),
            ("phone", "organization"),
        ]


